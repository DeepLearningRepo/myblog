import { chromium } from 'playwright-core';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';

const origin = process.env.PREVIEW_URL || 'http://127.0.0.1:4321';
const executablePath = process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const browser = await chromium.launch({ executablePath, headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, colorScheme: 'light' });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const posts = await (await fetch(`${origin}/search-index.json`)).json();
const firstArticle = posts.find(post => post.title === '布局代数（1）');
assert.ok(firstArticle, 'The first real article is missing');
assert.ok(!posts.some(post => /start-writing|markdown-guide|curiosity\/$/.test(post.url)), 'Sample drafts were published');
const articlePath = firstArticle.url;
await mkdir('artifacts', { recursive: true });
await page.goto(origin, { waitUntil: 'networkidle' });
await page.locator('.hero h1').waitFor();
assert.ok((await page.locator('.brand').textContent()).includes('Axis的想法'));
assert.equal(await page.locator('.hero h1').textContent(), '人生海海');
await page.screenshot({ path: 'artifacts/home-desktop.png', fullPage: true });
await page.screenshot({ path: 'artifacts/home-desktop-top.png', fullPage: false });
await page.locator('#theme-toggle').click();
assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
await page.reload({ waitUntil: 'networkidle' });
assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
await page.screenshot({ path: 'artifacts/home-dark.png', fullPage: true });
await page.screenshot({ path: 'artifacts/home-dark-top.png', fullPage: false });
await page.keyboard.press('Control+k');
await page.locator('#search-input').fill('布局代数');
await page.locator('.search-result').first().waitFor();
assert.ok(await page.locator('.search-result').count() > 0);
await page.keyboard.press('Escape');
await page.waitForFunction(() => !document.querySelector('#search-dialog').open);
assert.equal(await page.locator('#search-dialog').evaluate(el => el.open), false);
await page.locator('#theme-toggle').click();
await page.goto(`${origin}${articlePath}`, { waitUntil: 'networkidle' });
assert.ok(await page.locator('.katex').count() > 0);
assert.equal(await page.locator('.katex-error').count(), 0);
assert.equal(await page.locator('.katex-display .tag').count(), 6);
assert.ok(await page.locator('.toc a').count() > 0);
await page.locator('.prose img').first().scrollIntoViewIfNeeded();
await page.waitForFunction(() => [...document.querySelectorAll('.prose img')].every(image => image.complete && image.naturalWidth > 0));
assert.ok(await page.locator('.prose img').evaluateAll(images => images.length > 0 && images.every(image => image.complete && image.naturalWidth > 0)));
await page.locator('.prose a[href="#eq4"]').click();
assert.ok(page.url().endsWith('#eq4'));
await page.evaluate(() => scrollTo({ top: 0, behavior: 'instant' }));
await page.screenshot({ path: 'artifacts/article-desktop.png', fullPage: true });
await page.screenshot({ path: 'artifacts/article-desktop-top.png', fullPage: false });
const chineseMath = await page.locator('.katex annotation').allTextContents();
await page.locator('.language-switch a[lang="en"]').click();
assert.ok(page.url().includes('/en/posts/layout-algebra-1/'));
assert.equal(await page.locator('html').getAttribute('lang'), 'en');
assert.equal(await page.locator('.katex-display .tag').count(), 6);
assert.deepEqual(await page.locator('.katex annotation').allTextContents(), chineseMath, 'English formulas changed');
assert.ok(!/[\u3400-\u9fff]/.test(await page.locator('.article-header h1').textContent()));
await page.locator('.prose img').first().scrollIntoViewIfNeeded();
await page.waitForFunction(() => [...document.querySelectorAll('.prose img')].every(image => image.complete && image.naturalWidth > 0));
await page.evaluate(() => scrollTo({ top: 0, behavior: 'instant' }));
await page.screenshot({ path: 'artifacts/article-en-desktop.png', fullPage: true });
await page.screenshot({ path: 'artifacts/article-en-desktop-top.png', fullPage: false });
await page.locator('.language-switch a[lang="zh-CN"]').click();
assert.ok(!page.url().includes('/en/'));
await page.goto(`${origin}/en/`, { waitUntil: 'networkidle' });
await page.screenshot({ path: 'artifacts/home-en-desktop.png', fullPage: true });
await page.screenshot({ path: 'artifacts/home-en-desktop-top.png', fullPage: false });
await page.locator('#search-open').click();
await page.locator('#search-input').fill('tensor');
await page.locator('.search-result').first().waitFor();
assert.ok((await page.locator('.search-result').first().getAttribute('href')).includes('/en/posts/'));
await page.keyboard.press('Escape');
await page.goto(`${origin}/tags/`, { waitUntil: 'networkidle' });
await page.locator('.topic-card').filter({ hasText: '布局代数' }).click();
assert.ok(await page.locator('.post-card').count() > 0);
await page.setViewportSize({ width: 390, height: 844 });
for (const pathname of ['/', '/posts/', articlePath, '/tags/', '/about/', '/en/', '/en/posts/', `/en${articlePath}`, '/en/tags/', '/en/about/']) {
  await page.goto(`${origin}${pathname}`, { waitUntil: 'networkidle' });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Mobile overflow: ${pathname}`);
  if (pathname === '/') await page.screenshot({ path: 'artifacts/home-mobile.png', fullPage: true });
  if (pathname === articlePath) await page.screenshot({ path: 'artifacts/article-mobile.png', fullPage: true });
  if (pathname === `/en${articlePath}`) await page.screenshot({ path: 'artifacts/article-en-mobile.png', fullPage: true });
}
assert.deepEqual(errors, [], 'Browser errors');
const report = { desktop: '1440x1050', mobile: '390x844', article: firstArticle.title, checks: ['home', 'sample drafts excluded', 'theme toggle and persistence', 'Chinese and English search', 'escape closes dialog', 'tag navigation', 'article TOC', 'six equation numbers', 'formula (4) anchor', 'identical math in both languages', 'language switch keeps current article', 'article images loaded', 'mobile overflow on ten page types', 'no browser exceptions'], errors };
await writeFile('artifacts/browser-check.json', JSON.stringify(report, null, 2));
await browser.close();
console.log(JSON.stringify(report, null, 2));
